# Задание 1.1
# Записать число 42 десятью разными способами.
# Только запись числа (литерал), без арифметики и функций.
# Во всех вариантах должно выполняться 42 == 42

варианты = [
    ("42", 42),               # десятичная запись
    ("0x2A", 0x2A),           # шестнадцатеричная запись
    ("0o52", 0o52),           # восьмеричная запись
    ("0b101010", 0b101010),   # двоичная запись
    ("4_2", 4_2),             # подчёркивание вместо пробела
    ("0x_2A", 0x_2A),         # подчёркивание после 0x
    ("0o5_2", 0o5_2),         # то же в восьмеричной записи
    ("0b10_1010", 0b10_1010), # то же в двоичной записи
    ("+42", +42),             # унарный плюс (знак числа, не арифметика)
    ("-(-42)", -(-42)),       # двойной минус
    ("42.0", 42.0),           # дробное число, но 42.0 равно 42
    ("4.2e1", 4.2e1),         # экспоненциальная запись
]

for запись, число in варианты:
    print(f"{запись:>10} = {число!r:>6}   42 == это число? {число == 42}")

все_подходят = all(число == 42 for _, число in варианты)
print("Значит все", len(варианты), "способов дают 42:", все_подходят)

# Почему 42.0 тоже подходит:
# знак == сравнивает значение числа, а не его тип.
# Тип у 42 целый (int), а у 42.0 дробный (float), но значения равны.
print("42 == 42.0:", 42 == 42.0)
