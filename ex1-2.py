# Задание 1.2
# Есть ли ограничения на диапазон чисел в Python?
# Что с числами с плавающей запятой?
# Какое максимальное значение можно получить до переполнения?

import math
import sys

print("Версия Python:", sys.version.split()[0])
print()

# Целые числа (int) ограничений по величине не имеют.
print("Целые числа (int)")
print("  самое большое целое в sys.maxsize:", sys.maxsize)
print("  обычное число занимает", sys.getsizeof(10), "байт, а 10**20 уже", sys.getsizeof(10 ** 20), "байт")
большое = 2 ** 10000
print("  2**10000 содержит", len(str(большое)), "цифр, и это нормально")
print()

# Проверим, что int не переполняется при умножении:
print("  2**100 * 2**100 =", 2 ** 100 * 2 ** 100, " (число из", len(str((2 ** 100) ** 2)), "цифр)")
print("  в Си такое число дало бы переполнение, а в Python просто заняло память.")
print()

# Дробные числа (float) ограничены: это 64 бита, как double в Си.
print("Дробные числа (float, 64 бита)")
print("  максимум:", sys.float_info.max)
print("  минимум (нормальное число):", sys.float_info.min)
print("  самое маленькое положительное (денормальное):", 5e-324)
print("  машинная погрешность (эпсилон):", sys.float_info.epsilon)
print()

# Вот максимальное значение, которое удалось получить до переполнения:
максимум = sys.float_info.max
print("  МАКСИМУМ ДО ПЕРЕПОЛНЕНИЯ:", максимум)
print("  умножаем его на 10:", максимум * 10, " получилась бесконечность")
print("  или так:", 1e308 * 10)
print()

# Часть операций вместо бесконечности выдаёт ошибку:
for пример in ("2.0 ** 1024", "math.exp(1000)"):
    try:
        print(" ", пример, "=", eval(пример))
    except OverflowError as ошибка:
        print(f"  {пример} -> {type(ошибка).__name__}: {ошибка}")
print()

# Вниз числа тоже исчезают:
print("Вниз всё работает так же:", 1e-320, 1e-324, 5e-324)
print()

print("Вывод:")
print("  int   — ограничений нет, точность любая. Предел только память.")
print("  float — ограничен: максимум 1.7976931348623157e+308.")
print("          Дальше либо бесконечность (inf), либо ошибка OverflowError.")
print("  Ещё в Python 3.11+ есть лимит на печать очень длинного int")
print("  (4300 цифр), его можно поднять функцией sys.set_int_max_str_digits().")
