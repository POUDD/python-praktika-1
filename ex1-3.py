# Задание 1.3
# Найти встроенную (builtin) функцию, которая возвращает
# сразу два значения.

# Ответ: divmod(a, b) — от division (деление) и modulo (остаток).
# Возвращает кортеж из двух чисел: частное и остаток.

print("divmod(17, 5) =", divmod(17, 5))          # получилось (3, 2)
print("17 // 5 =", 17 // 5, "   17 % 5 =", 17 % 5)
print("То есть divmod делает то же самое, но за один вызов.")
print()

# Кортеж можно распаковать в две переменные:
частное, остаток = divmod(17, 5)
print(f"частное = {частное}, остаток = {остаток}, проверка {частное}*5+{остаток} = {частное * 5 + остаток}")
print()

# Остаток всегда того же знака, что и первое число (частное округляется вниз):
print("divmod(-17, 5) =", divmod(-17, 5))
print("divmod(17, -5) =", divmod(17, -5))
print()

# Работает и с дробными числами:
print("divmod(17.5, 0.5) =", divmod(17.5, 0.5))
print()

# Практический пример: разложить секунды на часы, минуты и секунды.
всего_секунд = 3725
часы, осталось = divmod(всего_секунд, 3600)
минуты, секунды = divmod(осталось, 60)
print(f"{всего_секунд} секунд это {часы} ч {минуты} мин {секунды} с")
