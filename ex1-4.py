# Задание 1.4
# С этим циклом что-то не так. Как это исправить?
#
# a = 10
# while a != 0:
#     a -= 0.1
#
# Что на самом деле такое 0.1 и можно ли увидеть его настоящее значение?

import math
from decimal import Decimal
from fractions import Fraction

# Почему цикл не заканчивается.
# 0.1 в Python — это дробное число (float), то есть двоичная дробь.
# А 1/10 в двоичной системе не пишется точно, получается бесконечная дробь.
# Поэтому 0.1 хранится как число, очень близкое к 0.1, но не равное ему.
# При вычитаниях ошибка копится, и a перескакивает через ноль, но
# ни разу не становится ровно 0.0. Значит условие a != 0 всегда верно
# и цикл работает бесконечно.

a = 10.0
самое_маленькое = None
for _ in range(1000):
    a -= 0.1
    if самое_маленькое is None or abs(a) < abs(самое_маленькое):
        самое_маленькое = a

print("Самое близкое к нулю значение a:", самое_маленькое)
print("Равно ли оно нулю?", самое_маленькое == 0)   # False, поэтому цикл и не кончается
print()

# Как увидеть настоящее значение 0.1.
print("Настоящее значение 0.1:")
print("  (0.1).hex() =", (0.1).hex())
print("  Decimal(0.1) =", Decimal(0.1))
print("  Fraction(0.1) =", Fraction(0.1))
print()

# Из-за этого получаются известные странности:
print("  0.1 + 0.2 =", 0.1 + 0.2)
print("  0.1 + 0.2 == 0.3:", 0.1 + 0.2 == 0.3)
print("  0.3 - 0.1 - 0.2 =", 0.3 - 0.1 - 0.2)
print()

# Как исправить. Первый способ: задать точное число повторов.
print("Способ 1: точное число повторов")
сумма = 0.0
for _ in range(100):      # ровно 100 раз по 0.1
    сумма += 0.1
print("  сумма 100 раз по 0.1 =", сумма, "(ошибка накопилась)")
print("  а 100 * 0.1 =", 100 * 0.1, "(умножение точнее)")
print()

# Второй способ: округлять значение после каждого шага.
print("Способ 2: округлять после каждого шага")
a = 10.0
шагов = 0
while a > 0:
    a = round(a - 0.1, 1)
    шагов += 1
print(f"  цикл закончился на a = {a} за {шагов} шагов")
print()

# Третий способ: сравнивать с нулём не строго, а с допуском.
print("Способ 3: сравнивать с допуском")
a = 10.0
шагов = 0
while not math.isclose(a, 0.0, abs_tol=1e-9):
    a -= 0.1
    шагов += 1
print(f"  цикл закончился на a = {a} за {шагов} шагов (это практически ноль)")
print()

# Четвёртый способ: десятичные числа Decimal, где 0.1 хранится точно.
print("Способ 4: числа Decimal (там 0.1 хранится точно)")
d = Decimal("10.0")
шагов = 0
while d > 0:
    d -= Decimal("0.1")
    шагов += 1
print(f"  цикл закончился ровно на d = {d} за {шагов} шагов")
