# Задание 1.5
# Программа зависает, хотя циклов нет. Почему?
#
# z = 1
# z <<= 40
# 2 ** z

import math

z = 1
z <<= 40            # сдвиг влево на 40 бит, то есть умножение на 2**40

print("z =", z, "(это 2**40)")

# Что просит посчитать строка 2 ** z?
цифр = int(z * math.log10(2)) + 1
print("в числе 2**z будет примерно", цифр, "десятичных цифр")
print("это", z // 8, "байт памяти, то есть", round(z / 8 / 1024 ** 3), "гигабайт")

# Переполнения не будет: целые числа в Python не ограничены по величине.
# Программа не зацикливается, а просто очень долго считает число,
# которое не помещается в память. Поэтому кажется, что она зависла.

# Насколько быстро растёт такое число (это уже можно посчитать):
for степень in (10, 100, 1000, 10000):
    число = 2 ** степень
    print(f"  2**{степень} -> цифр: {len(str(число))}")

print()
print("Вывод: ошибки нет, просто 2**2**40 это число из 3.3e11 цифр.")
print("У int нет ограничения по величине, поэтому вместо переполнения")
print("получается долгое вычисление, которое упирается в память.")
