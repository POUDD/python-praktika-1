# Этот код тоже зацикливается. А тут-то что не так?
#
# i = 0
# while i < 10:
#     print(i)
#     ++i

# В Python нет операторов ++ и --, как в Си или в Java.
# Запись ++i Python читает как +(+i), то есть два унарных плюса.
# Унарный плюс ничего не меняет, поэтому i остаётся равным 0,
# условие i < 10 всегда верно и программа бесконечно печатает 0.

# Проверим это (ограничим число повторов, чтобы самому не зависнуть):
i = 0
повторов = 0
while i < 10 and повторов < 5:
    print(i)
    ++i                # это +(+i), а не i += 1
    повторов += 1

print("i после ++i:", i, "(не изменился)")
print()

# Правильный вариант:
i = 0
while i < 10:
    print(i)
    i += 1            # вот так надо увеличивать на 1
print()

# Запись i++ (без знака =) вообще считается ошибкой,
# а вот ++i и --i допустимы, но ничего не делают (как и +i):
for код in ("i++", "i--"):
    try:
        compile(код, "проверка", "exec")
    except SyntaxError as ошибка:
        print(f"{код} -> {type(ошибка).__name__}: {ошибка.msg}")
