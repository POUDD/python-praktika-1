# Задание 1.8
# Объяснить, почему первый пример даёт True, а второй False.
#
# x = 5
# 1 < x < 10        -> True
#
# x = 5
# 1 < (x < 10)      -> False

# Первый пример: это цепочка сравнений.
# Python читает её как "1 < x и x < 10", то есть как (1 < x) and (x < 10).
# При x = 5 оба сравнения верны, поэтому ответ True.
# Значение x при этом вычисляется только один раз.

x = 5
print("1 < x < 10 =", 1 < x < 10)
print("проверка: (1 < x) and (x < 10) =", (1 < x) and (x < 10))
print("это одно и то же:", (1 < x < 10) == ((1 < x) and (x < 10)))
print()

# В цепочке может быть сколько угодно сравнений:
print("1 < x < 10 < 20 =", 1 < x < 10 < 20)
x = 10
print("а если x = 10, то 1 < x < 10 =", 1 < x < 10, "(второе сравнение неверно)")
x = 5
print()

# Второй пример: скобки всё поменяли.
# Сначала вычисляется внутреннее выражение (x < 10).
# Оно равно True, а True для Python это число 1.
# Потом сравнивается 1 < 1, а это False.

print("1 < (x < 10) =", 1 < (x < 10))
print("внутреннее выражение (x < 10) =", x < 10, "то есть True, а True это 1")
print("получается сравнение 1 < 1 =", 1 < 1)
print()

# Неожиданный случай, про который тоже стоит знать:
x = 5
print("x != 1 < 2 =", x != 1 < 2, "читается как (x != 1) and (1 < 2)")
print()

# Вывод:
# 1 < x < 10   это 1 < x и x < 10, поэтому True
# 1 < (x < 10) сначала считает x < 10 (это True, то есть 1), потом 1 < 1, поэтому False
