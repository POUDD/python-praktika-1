# Сводка по заданию 2: все 9 ошибок в одном запуске.
# Каждая ошибка также есть в отдельном файле ex2-1.py ... ex2-9.py.
# Этот файл их ловит сам и печатает список.

ошибки_синтаксиса = [
    ("2.1", "print(2 +* 3)"),
    ("2.2", "5 = 10"),
    ("2.4", 'print("Привет, мир!)'),
    ("2.6", 'if 5 > 3:\nprint("да")'),
    ("2.7", 'if 5 > 3:\n    print("да")\n  print("нет")'),
]

ошибки_при_запуске = [
    ("2.3", "print(несуществующая_переменная)"),
    ("2.5", 'print(10 + "десять")'),
    ("2.8", "import math; print(math.sqrt(-1))"),
    ("2.9", "import math; print(math.exp(1000))"),
]

print("Ошибки в коде (программа даже не запускается):")
for номер, код in ошибки_синтаксиса:
    try:
        compile(код, f"ex2-{номер}.py", "exec")
    except SyntaxError as ошибка:
        print(f"  {номер}  {type(ошибка).__name__}: {ошибка.msg}")

print()
print("Ошибки при запуске (код правильный, но программа упала):")
for номер, код in ошибки_при_запуске:
    try:
        exec(код, {})
    except Exception as ошибка:
        print(f"  {номер}  {type(ошибка).__name__}: {ошибка}")
